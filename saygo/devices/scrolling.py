"""Visual scrolling guidance shared by built-in model prompts."""

SCROLL_GUIDANCE = """滚动策略：
- 从截图选择目标列表内部的点；优先使用支持的 scroll_at(x,y,amount)，不要默认滚动整页。
- 浏览或寻找尚未出现的目标，首次请求约为目标区域可见高度的 50%，保留重叠内容。
- 接近目标时缩小到区域高度的 10%–20%；目标已经可见则停止滚动，定位后操作。
- 每次只滚动一次，再看新截图。比较同一条目或文字的位置，检查实际移动方向、距离和目标区域。
- 移动过大则减小下次幅度；移动偏小且确认仍有内容时再适度增大。越过目标时用小幅反向滚动。
- 没有变化时先检查滚动点、加载状态和列表边界；不要重复同样请求或盲目加大幅度。
- 浏览器 amount 正数向上、负数向下，1 单位请求 100 CSS 像素，支持小数。
  例如可见列表高 600 CSS 像素，向下半屏用 amount=-3，微调用 -0.6 至 -1.2。
  根据 screen_size 和目标区域占比估算高度；不要把缩放后的截图像素直接当 CSS 像素。
- 桌面等其他后端按 capabilities 的单位执行；没有像素换算时从小幅度开始观察，不能套用浏览器换算。
- 不支持 scroll_at 时只用该后端支持的滚动或滑动操作，每次操作后观察。
- 回执或画面稳定不等于目标达成；超时先观察，不自动补发，不断开浏览器插件。"""
